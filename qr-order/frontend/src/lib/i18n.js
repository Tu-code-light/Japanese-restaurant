export const translate = (language, key, values = {}) => {
  const template = messages[language]?.[key] ?? messages.vi[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
};

export const translateApiError = (language, message, status) => {
  const t = (key, values) => translate(language, key, values);
  if (!message) return status === 0 ? t('apiConnectionError') : t('requestFailed');
  if (language !== 'en') return message;
  if (apiMessages[message]) return t(apiMessages[message]);

  const duplicateTable = message.match(/^Bàn "(.+)" đã tồn tại$/);
  if (duplicateTable) return t('duplicateTable', { name: duplicateTable[1] });

  const unavailableItems = message.match(/^Món không còn phục vụ: (.+)$/);
  if (unavailableItems) return t('unavailableItems', { items: unavailableItems[1] });

  if (message.startsWith('Không thể chuyển đơn từ ')) return t('staleOrder');
  if (message.startsWith('Không tìm thấy route ')) return t('notFound');
  return message;
};

export function useTranslation() {
  const language = useLanguageStore((state) => state.language);
  const setLanguage = useLanguageStore((state) => state.setLanguage);
  const t = useCallback((key, values) => translate(language, key, values), [language]);
  return { language, setLanguage, t };
}
